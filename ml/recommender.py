"""
ml/recommender.py

Improved strict per-user personalized recommendation engine.

Production recommendations depend ONLY on the currently logged-in
user's own interaction history.

Allowed user signals:
    - views
    - likes
    - saves

Article representation:
    - TF-IDF article text
    - title + description TF-IDF
    - category
    - recency

Recommendation pipeline:

    User interactions
        ↓
    User preference profile
        ↓
    Candidate generation
        ↓
    Content similarity
        ↓
    Category preference
        ↓
    Recency
        ↓
    Personalized scoring
        ↓
    Diversity re-ranking
        ↓
    Top N recommendations

NOT used for production recommendations:
    - other users' interactions
    - global popularity
    - collaborative filtering
    - NCF predictions
    - shared user profiles

IMPORTANT:

The production feature catalogue is generated by:

    ml.feature_extraction

and is aligned to the live Article database using:

    Article.id ASC

The offline evaluation helper additionally verifies that a saved
feature row actually represents the current database Article by URL
or title before using the saved production feature catalogue.

This prevents numeric Article-ID collisions in isolated pytest
databases.
"""

