def get_user_interactions(
    user_id,
):
    """
    Return ONLY interactions belonging to user_id.

    No other user's interaction history is queried.
    """

    rows = (
        Interaction.query
        .filter_by(
            user_id=user_id
        )
        .order_by(
            Interaction.timestamp.asc(),
            Interaction.id.asc(),
        )
        .all()
    )

    return [
        (
            row.article_id,
            row.type,
        )
        for row in rows
    ]


# =====================================================================
# USER CATEGORY PREFERENCES
# =====================================================================

def build_user_category_preferences(
    user_id,
):
    """
    Build category preference scores from ONLY this user's history.

    Interaction weights:

        view -> 1
        like -> 2
        save -> 3
    """

    interactions = (
        get_user_interactions(
            user_id
        )
    )

    if not interactions:
        return {}

    category_scores = {}

    for (
        article_id,
        interaction_type,
    ) in interactions:

        article = db.session.get(
            Article,
            article_id,
        )

        if article is None:
            continue

        category = (
            safe_text(
                getattr(
                    article,
                    "category",
                    None,
                )
            ).lower()
            or "unknown"
        )

        weight = INTERACTION_WEIGHTS.get(
            interaction_type,
            1.0,
        )

        category_scores[
            category
        ] = (
            category_scores.get(
                category,
                0.0,
            )
            + weight
        )

    if not category_scores:
        return {}

    total = sum(
        category_scores.values()
    )

    if total <= 0:
        return {}

    return {
        category: score / total
        for (
            category,
            score,
        ) in category_scores.items()
    }


# =====================================================================
# BUILD USER CONTENT PROFILE
# =====================================================================

def build_user_profile_vector(
    user_id,
    text_matrix,
    title_matrix,
    article_id_to_row,
):
    """
    Build a personalized content profile from ONLY this user's
    interactions.

    Returns:

        (
            text_profile,
            title_profile,
            interacted_article_ids
        )
    """

    interactions = (
        get_user_interactions(
            user_id
        )
    )

    if not interactions:

        return (
            None,
            None,
            set(),
        )

    text_vectors = []

    title_vectors = []

    weights = []

    interacted_ids = set()

    for (
        article_id,
        interaction_type,
    ) in interactions:

        interacted_ids.add(
            article_id
        )

        row_number = (
            article_id_to_row.get(
                article_id
            )
        )

        if row_number is None:
            continue

        weight = INTERACTION_WEIGHTS.get(
            interaction_type,
            1.0,
        )

        text_vectors.append(
            text_matrix[
                row_number
            ].toarray()[0]
        )

        title_vectors.append(
            title_matrix[
                row_number
            ].toarray()[0]
        )

        weights.append(
            weight
        )

    if not text_vectors:

        return (
            None,
            None,
            interacted_ids,
        )

    text_vectors = np.asarray(
        text_vectors,
        dtype=float,
    )

    title_vectors = np.asarray(
        title_vectors,
        dtype=float,
    )

    weights = np.asarray(
        weights,
        dtype=float,
    ).reshape(
        -1,
        1,
    )

    total_weight = (
        weights.sum()
    )

    if total_weight <= 0:

        return (
            None,
            None,
            interacted_ids,
        )

    text_profile = (
        text_vectors
        * weights
    ).sum(
        axis=0
    ) / total_weight

    title_profile = (
        title_vectors
        * weights
    ).sum(
        axis=0
    ) / total_weight

    return (
        text_profile,
        title_profile,
        interacted_ids,
    )


