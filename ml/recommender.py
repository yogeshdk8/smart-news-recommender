def safe_text(value):
    """
    Return a normalized string representation.
    """

    if value is None:
        return ""

    return str(value).strip()


def normalize_scores(values):
    """
    Min-max normalize numeric values into approximately [0, 1].

    If all values are identical, return 0.5 for every value so that
    the feature does not completely disappear.
    """

    values = np.asarray(
        values,
        dtype=float,
    )

    if values.size == 0:
        return values

    minimum = np.min(
        values
    )

    maximum = np.max(
        values
    )

    if math.isclose(
        float(maximum),
        float(minimum),
    ):
        return np.full(
            values.shape,
            0.5,
            dtype=float,
        )

    return (
        values - minimum
    ) / (
        maximum - minimum
    )


