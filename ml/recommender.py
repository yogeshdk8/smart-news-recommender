# ARTICLE ID → FEATURE ROW MAPPING
# =====================================================================

def build_article_row_mapping(
    article_index,
):
    """
    Build a mapping between database Article IDs and feature rows.

    The current feature extractor stores the REAL database Article.id
    explicitly in articles_index.json.

    Therefore the normal production mapping is:

        Article.id -> feature row

    URL/title matching is retained as a compatibility mechanism for
    older indexes that might not contain explicit IDs.
    """

    row_by_article_id = {}

    # -----------------------------------------------------------------
    # First: use explicit Article IDs.
    # -----------------------------------------------------------------

    for row_number, item in enumerate(
        article_index
    ):

        possible_ids = [
            item.get("id"),
            item.get("article_id"),
        ]

        for value in possible_ids:

            if value is None:
                continue

            try:
                article_id = int(
                    value
                )

            except (
                TypeError,
                ValueError,
            ):
                continue

            row_by_article_id[
                article_id
            ] = row_number

    # -----------------------------------------------------------------
    # URL/title lookup tables.
    # -----------------------------------------------------------------

    rows_by_url = {}

    rows_by_title = {}

    for row_number, item in enumerate(
        article_index
    ):

        url = safe_text(
            item.get(
                "url"
            )
        )

        title = safe_text(
            item.get(
                "title"
            )
        )

        if url:

            rows_by_url[
                url
            ] = row_number

        if title:

            rows_by_title[
                title.lower()
            ] = row_number

    # -----------------------------------------------------------------
    # Compatibility matching against the current database.
    #
    # IMPORTANT:
    # Explicit IDs are trusted during normal production use because
    # feature_extraction.py now builds the index directly from the
    # database.
    #
    # URL/title matching is only needed for legacy indexes without IDs.
    # -----------------------------------------------------------------

    database_articles = (
        Article.query.all()
    )

    for article in database_articles:

        article_id = article.id

        if article_id in row_by_article_id:
            continue

        url = safe_text(
            getattr(
                article,
                "url",
                None,
            )
        )

        title = safe_text(
            getattr(
                article,
                "title",
                None,
            )
        )

        row_number = None

        if url:

            row_number = rows_by_url.get(
                url
            )

        if (
            row_number is None
            and title
        ):

            row_number = rows_by_title.get(
                title.lower()
            )

        if row_number is not None:

            row_by_article_id[
                article_id
            ] = row_number

    return row_by_article_id


# =====================================================================
# VERIFY SAVED FEATURE ROW AGAINST DATABASE ARTICLE
# =====================================================================

def artifact_row_matches_database_article(
    article_id,
    row_number,
    article_index,
):
    """
    Verify that a saved feature row actually represents the SAME
    database Article.

    This check is especially important for isolated pytest databases.

    Example problem:

        production Article.id = 1
        test Article.id       = 1

    The numeric ID is identical, but the articles are different.

    Therefore ID alone is not enough for the offline helper.

    Identity checks:

        1. URL, when available
        2. otherwise title

    Returns
    -------
    bool
        True when the saved row matches the current database Article.
    """

    if row_number is None:
        return False

    if (
        row_number < 0
        or row_number >= len(article_index)
    ):
        return False

    database_article = db.session.get(
        Article,
        article_id,
    )

    if database_article is None:
        return False

    indexed_article = article_index[
        row_number
    ]

    database_url = safe_text(
        getattr(
            database_article,
            "url",
            None,
        )
    )

    indexed_url = safe_text(
        indexed_article.get(
            "url"
        )
    )

    # ---------------------------------------------------------------
    # URL is the strongest available identity check.
    # ---------------------------------------------------------------

    if database_url or indexed_url:

        return (
            database_url
            == indexed_url
        )

    # ---------------------------------------------------------------
    # When URL is unavailable, compare titles.
    # ---------------------------------------------------------------

    database_title = safe_text(
        getattr(
            database_article,
            "title",
            None,
        )
    ).lower()

    indexed_title = safe_text(
        indexed_article.get(
            "title"
        )
    ).lower()

    return (
        database_title
        == indexed_title
    )


