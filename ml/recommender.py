def get_recency_score_from_matrix(
    recency_matrix,
    row_number,
):
    """
    Return the precomputed article recency score.
    """

    value = (
        recency_matrix[
            row_number
        ].toarray()[0][0]
    )

    return float(
        max(
            0.0,
            min(
                1.0,
                value,
            ),
        )
    )


