def popularity_ranking(
    exclude_ids=None,
    top_n=10,
):
    """
    Compatibility/test helper only.

    Return articles ordered by total interaction count.

    IMPORTANT:

        personalized_recommend() NEVER calls this function.

    Production recommendations remain strictly personalized.

    This function exists only because older tests or older code may
    still import it.
    """

    exclude_ids = set(
        exclude_ids or []
    )

    if top_n <= 0:
        return []

    rows = (
        db.session.query(
            Interaction.article_id,
            func.count(
                Interaction.id
            ).label(
                "interaction_count"
            ),
        )
        .group_by(
            Interaction.article_id
        )
        .order_by(
            func.count(
                Interaction.id
            ).desc()
        )
        .all()
    )

    recommendations = []

    for (
        article_id,
        interaction_count,
    ) in rows:

        if article_id in exclude_ids:
            continue

        recommendations.append(
            (
                article_id,
                float(
                    interaction_count
                ),
            )
        )

        if len(
            recommendations
        ) >= top_n:

            break

    return recommendations


