# MAIN PERSONALIZED RECOMMENDER
# =====================================================================

def personalized_recommend(
    user_id,
    top_n=20,
    candidate_pool_size=None,
):
    """
    Generate strictly personalized recommendations.

    IMPORTANT:

        Recommendations depend ONLY on the current user's own
        interactions.

    They do NOT use:

        - another user's interactions
        - global popularity
        - NCF
        - collaborative filtering

    Steps:

        1. Load article features.
        2. Build Article ID -> feature-row mapping.
        3. Read only current user's interactions.
        4. Build the user's weighted content profile.
        5. Build the user's category preferences.
        6. Calculate article similarities.
        7. Generate candidates.
        8. Calculate personalized scores.
        9. Apply diversity re-ranking.
        10. Return Top N.
    """

    if top_n <= 0:
        return []

    if candidate_pool_size is None:

        candidate_pool_size = max(
            DEFAULT_CANDIDATE_POOL,
            top_n * 5,
        )

    # -----------------------------------------------------------------
    # STEP 1
    # Load article feature artifacts.
    # -----------------------------------------------------------------

    artifacts = (
        load_content_artifacts()
    )

    text_matrix = artifacts[
        "text_matrix"
    ]

    title_matrix = artifacts[
        "title_matrix"
    ]

    recency_matrix = artifacts[
        "recency_matrix"
    ]

    feature_matrix = artifacts[
        "feature_matrix"
    ]

    article_index = artifacts[
        "article_index"
    ]

    # -----------------------------------------------------------------
    # STEP 2
    # Build Article ID -> feature-row mapping.
    # -----------------------------------------------------------------

    article_id_to_row = (
        build_article_row_mapping(
            article_index
        )
    )

    # -----------------------------------------------------------------
    # Build row -> Article ID mapping.
    # -----------------------------------------------------------------

    article_ids = [
        None
        for _ in article_index
    ]

    for (
        article_id,
        row_number,
    ) in article_id_to_row.items():

        if (
            0 <= row_number
            < len(article_ids)
        ):

            article_ids[
                row_number
            ] = article_id

    # -----------------------------------------------------------------
    # Validate mapping.
    # -----------------------------------------------------------------

    if not all(
        article_id is not None
        for article_id in article_ids
    ):

        missing_rows = [
            row_number
            for row_number, article_id
            in enumerate(article_ids)
            if article_id is None
        ]

        raise RuntimeError(
            "Some feature rows could not be mapped to database "
            "Article IDs.\n"
            f"Missing feature rows: "
            f"{missing_rows[:20]}\n"
            f"Total missing rows: "
            f"{len(missing_rows)}\n\n"
            "Run:\n"
            "    python -m ml.feature_extraction\n"
            "to rebuild the database-aligned feature catalogue."
        )

    # -----------------------------------------------------------------
    # STEP 3
    # Get ONLY this user's interactions.
    # -----------------------------------------------------------------

    interactions = (
        get_user_interactions(
            user_id
        )
    )

    # Strict cold-start behavior.
    #
    # No popularity fallback.
    # No other user's profile.

    if not interactions:
        return []

    # -----------------------------------------------------------------
    # STEP 4
    # Build current user's content profile.
    # -----------------------------------------------------------------

    (
        text_profile,
        title_profile,
        interacted_ids,
    ) = build_user_profile_vector(
        user_id=user_id,
        text_matrix=text_matrix,
        title_matrix=title_matrix,
        article_id_to_row=article_id_to_row,
    )

    if (
        text_profile is None
        or title_profile is None
    ):
        return []

    # -----------------------------------------------------------------
    # STEP 5
    # Build current user's category preferences.
    # -----------------------------------------------------------------

    category_preferences = (
        build_user_category_preferences(
            user_id
        )
    )

    category_by_row = (
        build_category_by_row(
            article_index
        )
    )

    # -----------------------------------------------------------------
    # STEP 6
    # Calculate similarity to user's profile.
    # -----------------------------------------------------------------

    text_profile = (
        text_profile.reshape(
            1,
            -1,
        )
    )

    title_profile = (
        title_profile.reshape(
            1,
            -1,
        )
    )

    text_similarities = (
        cosine_similarity(
            text_profile,
            text_matrix,
        ).flatten()
    )

    title_similarities = (
        cosine_similarity(
            title_profile,
            title_matrix,
        ).flatten()
    )

    # -----------------------------------------------------------------
    # STEP 7
    # Generate candidates.
    # -----------------------------------------------------------------

    candidates = generate_candidates(
        text_similarities=text_similarities,
        title_similarities=title_similarities,
        interacted_ids=interacted_ids,
        article_ids=article_ids,
        article_id_to_row=article_id_to_row,
        candidate_pool_size=candidate_pool_size,
    )

    if not candidates:
        return []

    # -----------------------------------------------------------------
    # STEP 8
    # Personalized scoring.
    # -----------------------------------------------------------------

    scored_candidates = (
        calculate_personalized_scores(
            candidates=candidates,
            text_similarities=text_similarities,
            title_similarities=title_similarities,
            category_preferences=category_preferences,
            category_by_row=category_by_row,
            recency_matrix=recency_matrix,
        )
    )

    if not scored_candidates:
        return []

    # -----------------------------------------------------------------
    # STEP 9
    # Diversity re-ranking.
    # -----------------------------------------------------------------

    reranked = diversity_rerank(
        scored_candidates=scored_candidates,
        feature_matrix=feature_matrix,
        category_by_row=category_by_row,
        top_n=top_n,
    )

    # -----------------------------------------------------------------
    # STEP 10
    # Return article IDs and personalized scores.
    # -----------------------------------------------------------------

    return [
        (
            candidate[
                "article_id"
            ],
            float(
                candidate[
                    "score"
                ]
            ),
        )
        for candidate in reranked
    ]


# =====================================================================
# OFFLINE EVALUATION RECOMMENDER
# =====================================================================

def recommend_from_interactions(
    interactions,
    exclude_ids=None,
    top_n=10,
):
    """
    Generate recommendations from an explicit interaction list.

    This function is used by the offline evaluation system.

    IMPORTANT:

        It uses ONLY the interactions supplied to this function.

        It does NOT query another user's interaction history to build
        the recommendation profile.

    Normal operation uses the production feature catalogue.

    Special isolated-database behavior:

        If the interaction Article IDs collide numerically with IDs
        in the production feature catalogue but the URLs/titles do
        not match, a temporary TF-IDF catalogue is built from the
        CURRENT database.

    That protects pytest and other isolated evaluation environments.
    """

    # -----------------------------------------------------------------
    # Basic argument validation.
    # -----------------------------------------------------------------

    if top_n <= 0:
        return []

    interactions = list(
        interactions
    )

    if not interactions:
        return []

    exclude_ids = set(
        exclude_ids or []
    )

    interaction_article_ids = {
        article_id
        for (
            article_id,
            _interaction_type,
        ) in interactions
    }

    # -----------------------------------------------------------------
    # STEP 1
    # Load production feature artifacts.
    # -----------------------------------------------------------------

    artifacts = (
        load_content_artifacts()
    )

    article_index = artifacts[
        "article_index"
    ]

    article_id_to_row = (
        build_article_row_mapping(
            article_index
        )
    )

    # -----------------------------------------------------------------
    # STEP 2
    # Verify that the saved feature rows really represent the current
    # database articles.
    #
    # IMPORTANT:
    #
    # ID collision example:
    #
    # production Article 1 != pytest Article 1
    #
    # So numeric ID alone is NOT enough here.
    # -----------------------------------------------------------------

    artifact_mapping_usable = True

    for article_id in (
        interaction_article_ids
    ):

        row_number = (
            article_id_to_row.get(
                article_id
            )
        )

        if not artifact_row_matches_database_article(
            article_id=article_id,
            row_number=row_number,
            article_index=article_index,
        ):

            artifact_mapping_usable = False
            break

    # -----------------------------------------------------------------
    # STEP 3
    # Temporary database fallback.
    #
    # This path is primarily for isolated unit-test databases and other
    # situations where the current Article records do not correspond
    # to the saved production feature catalogue.
    #
    # IMPORTANT:
    #
    # This helper uses ONLY the explicit interaction list supplied to
    # the function.
    #
    # It does NOT use another user's interaction history.
    #
    # Production personalized_recommend() does NOT use this fallback.
    # -----------------------------------------------------------------

    if not artifact_mapping_usable:

        articles = (
            Article.query
            .order_by(
                Article.id.asc()
            )
            .all()
        )

        if not articles:
            return []

        article_ids = [
            article.id
            for article in articles
        ]

        # -------------------------------------------------------------
        # Build text corpus from current database records.
        # -------------------------------------------------------------

        def build_fallback_text(
            article,
        ):
            fields = [
                getattr(
                    article,
                    "title",
                    None,
                ),
                getattr(
                    article,
                    "description",
                    None,
                ),
                getattr(
                    article,
                    "content",
                    None,
                ),
                getattr(
                    article,
                    "cleaned_text",
                    None,
                ),
            ]

            parts = [
                safe_text(
                    value
                )
                for value in fields
                if safe_text(
                    value
                )
            ]

            text = " ".join(
                parts
            ).strip()

            if not text:
                text = "article"

            return text

        corpus = [
            build_fallback_text(
                article
            )
            for article in articles
        ]

        if not any(
            text.strip()
            for text in corpus
        ):
            return []

        # -------------------------------------------------------------
        # Build temporary TF-IDF.
        # -------------------------------------------------------------

        vectorizer = (
            TfidfVectorizer(
                max_features=5000,
                min_df=1,
                ngram_range=(1, 2),
                sublinear_tf=True,
            )
        )

        try:

            matrix = (
                vectorizer.fit_transform(
                    corpus
                )
            )

        except ValueError:

            return []

        # -------------------------------------------------------------
        # Temporary Article ID -> row mapping.
        # -------------------------------------------------------------

        fallback_row_by_id = {
            article_id: row_number
            for (
                row_number,
                article_id,
            ) in enumerate(
                article_ids
            )
        }

        # -------------------------------------------------------------
        # Build explicit user's profile.
        # -------------------------------------------------------------

        profile_vectors = []

        profile_weights = []

        for (
            article_id,
            interaction_type,
        ) in interactions:

            row_number = (
                fallback_row_by_id.get(
                    article_id
                )
            )

            if row_number is None:
                continue

            weight = (
                INTERACTION_WEIGHTS.get(
                    interaction_type,
                    1.0,
                )
            )

            profile_vectors.append(
                matrix[
                    row_number
                ].toarray()[0]
            )

            profile_weights.append(
                weight
            )

        if not profile_vectors:
            return []

        profile_vectors = np.asarray(
            profile_vectors,
            dtype=float,
        )

        profile_weights = np.asarray(
            profile_weights,
            dtype=float,
        ).reshape(
            -1,
            1,
        )

        total_weight = (
            profile_weights.sum()
        )

        if total_weight <= 0:
            return []

        profile = (
            profile_vectors
            * profile_weights
        ).sum(
            axis=0
        ) / total_weight

        # -------------------------------------------------------------
        # Calculate similarities.
        # -------------------------------------------------------------

        similarities = (
            cosine_similarity(
                profile.reshape(
                    1,
                    -1,
                ),
                matrix,
            ).flatten()
        )

        # -------------------------------------------------------------
        # Never recommend explicit interaction/excluded articles.
        # -------------------------------------------------------------

        interacted_ids = set(
            exclude_ids
        )

        interacted_ids.update(
            interaction_article_ids
        )

        recommendations = []

        for (
            row_number,
            article_id,
        ) in enumerate(
            article_ids
        ):

            if article_id in interacted_ids:
                continue

            recommendations.append(
                (
                    article_id,
                    float(
                        similarities[
                            row_number
                        ]
                    ),
                )
            )

        recommendations.sort(
            key=lambda item: item[1],
            reverse=True,
        )

        return recommendations[
            :top_n
        ]

    # -----------------------------------------------------------------
    # STEP 4
    # Normal production-artifact path.
    # -----------------------------------------------------------------

    text_matrix = artifacts[
        "text_matrix"
    ]

    title_matrix = artifacts[
        "title_matrix"
    ]

    recency_matrix = artifacts[
        "recency_matrix"
    ]

    feature_matrix = artifacts[
        "feature_matrix"
    ]

    # -----------------------------------------------------------------
    # Build row -> Article ID mapping.
    # -----------------------------------------------------------------

    article_ids = [
        None
        for _ in article_index
    ]

    for (
        article_id,
        row_number,
    ) in article_id_to_row.items():

        if (
            0 <= row_number
            < len(article_ids)
        ):

            article_ids[
                row_number
            ] = article_id

    if not all(
        article_id is not None
        for article_id in article_ids
    ):

        return []

    # -----------------------------------------------------------------
    # STEP 5
    # Build explicit user's profile.
    # -----------------------------------------------------------------

    text_vectors = []

    title_vectors = []

    weights = []

    interacted_ids = set(
        exclude_ids
    )

    for (
        article_id,
        interaction_type,
    ) in interactions:

        interacted_ids.add(
            article_id
        )

        row_number = (
            article_id_to_row.get(
                article_id
            )
        )

        if row_number is None:
            continue

        weight = (
            INTERACTION_WEIGHTS.get(
                interaction_type,
                1.0,
            )
        )

        text_vectors.append(
            text_matrix[
                row_number
            ].toarray()[0]
        )

        title_vectors.append(
            title_matrix[
                row_number
            ].toarray()[0]
        )

        weights.append(
            weight
        )

    if not text_vectors:
        return []

    text_vectors = np.asarray(
        text_vectors,
        dtype=float,
    )

    title_vectors = np.asarray(
        title_vectors,
        dtype=float,
    )

    weights = np.asarray(
        weights,
        dtype=float,
    ).reshape(
        -1,
        1,
    )

    total_weight = (
        weights.sum()
    )

    if total_weight <= 0:
        return []

    text_profile = (
        text_vectors
        * weights
    ).sum(
        axis=0
    ) / total_weight

    title_profile = (
        title_vectors
        * weights
    ).sum(
        axis=0
    ) / total_weight

    # -----------------------------------------------------------------
    # STEP 6
    # Calculate similarities.
    # -----------------------------------------------------------------

    text_similarities = (
        cosine_similarity(
            text_profile.reshape(
                1,
                -1,
            ),
            text_matrix,
        ).flatten()
    )

    title_similarities = (
        cosine_similarity(
            title_profile.reshape(
                1,
                -1,
            ),
            title_matrix,
        ).flatten()
    )

    # -----------------------------------------------------------------
    # STEP 7
    # Build category preferences using ONLY explicit interactions.
    # -----------------------------------------------------------------

    category_scores = {}

    for (
        article_id,
        interaction_type,
    ) in interactions:

        article = db.session.get(
            Article,
            article_id,
        )

        if article is None:
            continue

        category = (
            safe_text(
                getattr(
                    article,
                    "category",
                    None,
                )
            ).lower()
            or "unknown"
        )

        weight = (
            INTERACTION_WEIGHTS.get(
                interaction_type,
                1.0,
            )
        )

        category_scores[
            category
        ] = (
            category_scores.get(
                category,
                0.0,
            )
            + weight
        )

    category_total = sum(
        category_scores.values()
    )

    if category_total > 0:

        category_preferences = {
            category: score / category_total
            for (
                category,
                score,
            ) in category_scores.items()
        }

    else:

        category_preferences = {}

    category_by_row = (
        build_category_by_row(
            article_index
        )
    )

    # -----------------------------------------------------------------
    # STEP 8
    # Generate candidates.
    # -----------------------------------------------------------------

    candidates = generate_candidates(
        text_similarities=text_similarities,
        title_similarities=title_similarities,
        interacted_ids=interacted_ids,
        article_ids=article_ids,
        article_id_to_row=article_id_to_row,
        candidate_pool_size=max(
            DEFAULT_CANDIDATE_POOL,
            top_n * 5,
        ),
    )

    if not candidates:
        return []

    # -----------------------------------------------------------------
    # STEP 9
    # Calculate personalized scores.
    # -----------------------------------------------------------------

    scored_candidates = (
        calculate_personalized_scores(
            candidates=candidates,
            text_similarities=text_similarities,
            title_similarities=title_similarities,
            category_preferences=category_preferences,
            category_by_row=category_by_row,
            recency_matrix=recency_matrix,
        )
    )

    if not scored_candidates:
        return []

    # -----------------------------------------------------------------
    # STEP 10
    # Diversity re-ranking.
    # -----------------------------------------------------------------

    reranked = diversity_rerank(
        scored_candidates=scored_candidates,
        feature_matrix=feature_matrix,
        category_by_row=category_by_row,
        top_n=top_n,
    )

    return [
        (
            candidate[
                "article_id"
            ],
            float(
                candidate[
                    "score"
                ]
            ),
        )
        for candidate in reranked
    ]


